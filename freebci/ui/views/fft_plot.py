    def backpushButton_click(self):
        self.stackedWidget.setCurrentIndex(0)

    
    def chanChooseBox_click(self):
        self.stackedWidget.setCurrentIndex(1)

    
    def ischan_pushButton_click(self, _chan):
        if self.FFTactiveChannels[_chan]:
            self.ischan_pushButtons[_chan].setStyleSheet('border :2px solid ;border-color: cyan; background: gray; color: white')
        else:
            self.ischan_pushButtons[_chan].setStyleSheet('border :2px solid ;border-color: cyan; background: dark blue; color: white')
        self.FFTactiveChannels[_chan] = not self.FFTactiveChannels[_chan]
        self.ischan_pushButtons[self._chan].setStyleSheet('border :2px solid ;border-color: cyan; background: gray; color: white')

    
    def all_button_click(self, _chan):
        if self.FFTactiveChannels[_chan] == False:
            for i in range(self._chan):
                self.ischan_pushButtons[i].setStyleSheet('border :2px solid ;border-color: cyan; background: dark blue; color: white')
                self.FFTactiveChannels[i] = not self.FFTactiveChannels[i]
            self.ischan_pushButtons[_chan].setStyleSheet('border :2px solid ;border-color: cyan; background: dark blue; color: white')
        self.FFTactiveChannels[_chan] = not self.FFTactiveChannels[_chan]

    
    def all_clear(self, _chan):
        if self.FFTactiveChannels[_chan] == False:
            for i in range(self._chan):
                self.ischan_pushButtons[i].setStyleSheet('border :2px solid ;border-color: cyan; background: gray; color: white')
                self.FFTactiveChannels[i] = False
            self.ischan_pushButtons[_chan].setStyleSheet('border :2px solid ;border-color: cyan; background: gray; color: white')
        self.ischan_pushButtons[self._chan].setStyleSheet('border :2px solid ;border-color: cyan; background: gray; color: white')

    
